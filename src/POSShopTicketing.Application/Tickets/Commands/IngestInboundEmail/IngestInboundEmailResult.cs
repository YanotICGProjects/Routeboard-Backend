namespace POSShopTicketing.Application.Tickets.Commands.IngestInboundEmail;

public enum InboundEmailOutcome
{
    TicketCreated,
    MessageAppended,
    Duplicate,
    IgnoredUnknownMailbox,
    IgnoredAutoGenerated,
    IgnoredInvalid,
    IgnoredRateLimited
}

/// <summary>
/// Ignored/duplicate outcomes are NORMAL results, not errors: the
/// controller still answers HTTP 200 so the provider stops retrying.
/// </summary>
public record IngestInboundEmailResult(
    InboundEmailOutcome Outcome, Guid? TicketId, string? TicketNumber, Guid? MessageId, bool IsUnverified)
{
    public bool IsNewTicket => Outcome == InboundEmailOutcome.TicketCreated;

    public static IngestInboundEmailResult Ignored(InboundEmailOutcome outcome) =>
        new(outcome, null, null, null, false);
}